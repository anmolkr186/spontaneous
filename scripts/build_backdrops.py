#!/usr/bin/env python3
"""Turn the source images in backdrops/ into the app's backdrop library.

  backdrops/natural/*.jpg             -> public/backdrops/natural/<slug>.webp (2400px wide) + thumbs/<slug>.webp (480px)
  backdrops/ascii-and-gradient/*.jpg  -> public/backdrops/gradient/...
  writes src/editor/backdrops.gen.ts  (the manifest the editor reads)

Run again after adding images: python3 scripts/build_backdrops.py
Needs `sips` (macOS) and `cwebp`.
"""
import json, re, subprocess, sys, tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SETS = [("natural", "natural", "Natural"), ("ascii-and-gradient", "gradient", "Gradient & ASCII")]
FULL, THUMB = 2400, 480


def slug(name: str) -> str:
    s = re.sub(r"[^a-z0-9]+", "-", name.lower()).strip("-")
    return s or "untitled"


def label(name: str) -> str:
    return re.sub(r"\s+", " ", name.replace("_", " ")).strip(" -") or "Untitled"


def webp(src: Path, out: Path, width: int, quality: int) -> None:
    out.parent.mkdir(parents=True, exist_ok=True)
    if out.exists() and out.stat().st_mtime > src.stat().st_mtime:
        return
    # Never upscale: the sources are about 1440px wide.
    info = subprocess.run(["sips", "-g", "pixelWidth", str(src)], check=True, capture_output=True, text=True).stdout
    width = min(width, int(info.split()[-1]))
    with tempfile.TemporaryDirectory() as tmp:
        png = Path(tmp) / "x.png"
        subprocess.run(["sips", "-s", "format", "png", "--resampleWidth", str(width), str(src), "--out", str(png)], check=True, capture_output=True)
        subprocess.run(["cwebp", "-quiet", "-q", str(quality), "-m", "6", str(png), "-o", str(out)], check=True)


def main() -> None:
    entries = []
    for folder, set_id, _ in SETS:
        src_dir = ROOT / "backdrops" / folder
        seen: set[str] = set()
        for src in sorted(src_dir.glob("*.jpg"), key=lambda p: p.name.lower()):
            base = slug(src.stem)
            s, n = base, 2
            while s in seen:
                s, n = f"{base}-{n}", n + 1
            seen.add(s)
            out = ROOT / "public" / "backdrops" / set_id
            webp(src, out / f"{s}.webp", FULL, 82)
            webp(src, out / "thumbs" / f"{s}.webp", THUMB, 72)
            entries.append({"id": f"{set_id}/{s}", "set": set_id, "label": label(src.stem)})
            print(f"{set_id}/{s}", file=sys.stderr)
    body = ",\n".join(f"  {json.dumps(e)}" for e in entries)
    (ROOT / "src" / "editor" / "backdrops.gen.ts").write_text(
        "// Generated by scripts/build_backdrops.py from backdrops/. Do not edit by hand.\n"
        "export const BACKDROP_IMAGES: { id: string; set: \"natural\" | \"gradient\"; label: string }[] = [\n"
        f"{body},\n];\n"
    )


if __name__ == "__main__":
    main()
